"""Expected values for the tests of the model options of stage 3 (switch clock, AFT effect of the switch, switch
before progression, censoring of PFS only).

Run from this folder with:  python3 expected_model5.py [model] [cross] [mc]
Requires numpy and scipy (about 10 minutes, most of it for the Monte Carlo part). Results are written to
results/model5_*.csv and read by the tests in tests/testthat (helper-expected.R). The models and scenarios are
defined identically in tests/testthat/helper-scenarios.R (models_s3(), scn_s3()).

Files:
  model5_states.csv  state probabilities and the OS and PFS survival functions and densities of single groups;
                     reference: ref_model5 (adaptive quadrature over the switch and progression times; matrix
                     exponentials for the Markov models, checked against the quadrature in model5_markov.csv)
  model5_post.csv    post-progression quantities between two clock values (switch clock and AFT effect);
                     reference: ref_model5.post (adaptive quadrature over the switch time)
  model5_from5.csv   survival and death density from the switched progression-free state; reference:
                     ref_model5.from5
  model5_markov.csv  maximum differences between the quadrature and the matrix exponentials (Markov models)
  model5_events.csv  expected PFS and OS events and censorings by group in two Markov scenarios; reference:
                     adaptive quadrature with the enrolled fraction inside the integrand
  model5_cross.csv   per-patient E[r_P(t_p) r_O(t_o)] in two Markov scenarios; reference: ref_cross5
  model5_cross_mc.csv  Monte Carlo estimates (10 million patients) of E[r_P(t_p) r_O(t_o)] with standard errors in
                     four scenarios that are not Markov or not both; patients generated by ref_model5.simulate
"""
import csv
import os
import sys
import time

import numpy as np
from numpy.polynomial import chebyshev as cheb
from scipy import integrate

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
import ref_cross5 as rc  # noqa: E402
import ref_logrank as rl  # noqa: E402
import ref_model5 as r5  # noqa: E402

OUT = os.path.join(HERE, "results")
KEYS = ["psi", "phi", "dlt"]
TIMES = [1.0, 3.5, 6.0, 12.0, 20.0, 35.0]


def write(name, rows):
    os.makedirs(OUT, exist_ok=True)
    path = os.path.join(OUT, name)
    keys = list(rows[0].keys())
    with open(path, "w", newline="") as f:
        w = csv.DictWriter(f, fieldnames=keys, lineterminator="\n")
        w.writeheader()
        for r in rows:
            w.writerow({k: (repr(float(v)) if isinstance(v, (float, np.floating)) else v) for k, v in r.items()})
    print("wrote", path, flush=True)


# models (helper-scenarios.R: models_s3()) ---------------------------------------------------------------------
BASE_C = dict(time=[0, 4], prog=[0.10, 0.08], death=0.01, switch_prob=0.3, time_post=[0, 3],
              death_prog=[0.05, 0.06], switch_rate=0.04, death_switch=[0.03, 0.035], dropout=0.005)
BASE_T = dict(time=[0, 4], prog=[0.06, 0.05], death=0.008, switch_prob=0.0, time_post=[0, 3],
              death_prog=[0.045, 0.05], switch_rate=0.0, dropout=0.005)
PRE = dict(switch_pre=[0.03, 0.02], prog_switch=[0.07, 0.06], death_switch_pre=0.007)


def model(name, clock, pfs_switch="event"):
    """Control-group models of the tests (and the treatment group 'T' with a switch before progression)."""
    kw = dict(BASE_C)
    if name == "P":            # switch before progression
        kw.update(PRE)
    elif name == "P2":         # piecewise intensities of state 5
        kw.update(switch_pre=[0.05, 0.01], prog_switch=[0.04, 0.09], death_switch_pre=[0.012, 0.004])
    elif name == "Z":          # progression only after a switch before progression
        kw = dict(time=[0, 4], death=0.01, switch_pre=[0.03, 0.02], prog_switch=[0.07, 0.06],
                  time_post=[0, 3], death_switch=[0.03, 0.035], dropout=0.005)
    elif name in ("A06", "A15"):   # AFT effect of the switch
        kw.pop("death_switch")
        kw.update(switch_af=0.6 if name == "A06" else 1.5)
    elif name == "W":          # death after a switch on the time since the switch
        kw.update(switch_clock="switch")
    elif name == "T":
        kw = dict(BASE_T)
        kw.update(switch_pre=0.01)
    elif name == "T0":
        kw = dict(BASE_T)
    else:
        raise ValueError(name)
    death = kw.pop("death")
    return r5.Model5(death, clock=clock, pfs_switch=pfs_switch, **kw)


def model_post(name):
    """Post-progression parameters for model5_post.csv (three intervals of time_post)."""
    kw = dict(death=0.01, time_post=[0, 3, 8], death_prog=[0.05, 0.08, 0.04], switch_rate=[0.04, 0.06, 0.02])
    if name == "switch":
        kw.update(death_switch=[0.03, 0.05, 0.02], switch_clock="switch")
    else:
        kw.update(switch_af=float(name[3:]))
    death = kw.pop("death")
    return r5.Model5(death, **kw)


# scenarios (helper-scenarios.R: scn_s3()) ------------------------------------------------------------------------
ACC = rl.Accrual(time=[0, 6], prop=[0.3, 0.7], duration=18)
N = 500


def scenario(name):
    """Control and treatment models of the scenarios of the PFS-OS products."""
    if name == "PF":           # forward, switch before progression, PFS followed up
        c, t = model("P", "forward"), model("T", "forward")
    elif name == "PFC":        # forward, PFS censored at the switch, censoring of PFS only in the control group
        c, t = model("P", "forward", "censor"), model("T", "forward", "censor")
        c.dropout_pfs = np.array([0.02, 0.02])
    elif name == "PR":         # reset, PFS followed up
        c, t = model("P", "reset"), model("T", "reset")
    elif name == "PRC":        # reset, PFS censored at the switch
        c, t = model("P", "reset", "censor"), model("T", "reset", "censor")
    elif name == "AR":         # reset, AFT effect (0.6) in the control group, censoring of PFS only
        c, t = model("A06", "reset"), model("T0", "reset")
        c.dropout_pfs = np.array([0.02, 0.03])
        t.dropout_pfs = np.array([0.015, 0.015])
    elif name == "WF":         # forward, switch clock in the control group, switch before progression (censor)
        c, t = model("W", "forward", "censor"), model("T", "forward", "censor")
        c.switch_pre = np.array([0.02, 0.02])
    else:
        raise ValueError(name)
    return [c, t]


# part 1: single groups -------------------------------------------------------------------------------------------
def part_model():
    rows, mk = [], []
    for name in ("P", "P2", "Z", "A06", "A15", "W"):
        for clock in ("reset", "forward"):
            for pfs in ("event", "censor") if name in ("P", "P2", "Z") else ("event",):
                m = model(name, clock, pfs)
                t0 = time.time()
                for s in TIMES:
                    st = r5.states(m, s)
                    row = dict(model=name, clock=clock, pfs_switch=pfs, time=s, p1=st[0], p5=st[1], p2=st[2],
                               p3=st[3], p4=st[4], os_surv=r5.os_surv(m, s), os_dens=r5.os_dens(m, s),
                               pfs_surv=r5.pfs_surv(m, s), pfs_dens=r5.pfs_dens(m, s))
                    rows.append(row)
                    if r5.is_markov(m):
                        q = r5.markov_quantities(m, s)
                        mk.append(max(np.max(np.abs(q["states"] - st)), abs(q["os_surv"] - row["os_surv"]),
                                      abs(q["os_dens"] - row["os_dens"]), abs(q["pfs_surv"] - row["pfs_surv"]),
                                      abs(q["pfs_dens"] - row["pfs_dens"])))
                print(name, clock, pfs, "%.1fs" % (time.time() - t0), flush=True)
    write("model5_states.csv", rows)
    write("model5_markov.csv", [dict(quantity="max abs difference quadrature vs expm", value=max(mk), n=len(mk))])
    pairs = [(0.0, 1.0), (0.0, 2.5), (0.0, 5.0), (0.0, 9.0), (0.0, 20.0), (1.5, 4.0), (2.0, 7.5), (3.5, 12.0)]
    rows = []
    for name in ("switch", "aft0.6", "aft1.5"):
        m = model_post(name)
        for a, b in pairs:
            q = r5.post(m, a, b)
            rows.append({"model": name, "from": a, "to": b, "r22": q["r22"], "r23": q["q23"], "r33": q["s33"],
                         "f23": q["f23"], "f33": q["f33"]})
    write("model5_post.csv", rows)
    pairs5 = [(0.0, 2.0), (1.0, 6.0), (3.0, 10.0), (5.0, 25.0), (2.5, 40.0)]
    rows = []
    for name in ("P", "P2"):
        for clock in ("reset", "forward"):
            m = model(name, clock)
            for w, u in pairs5:
                sv, dv = r5.from5(m, w, u)
                rows.append(dict(model=name, clock=clock, w=w, u=u, surv=sv, dens=dv))
    write("model5_from5.csv", rows)


# part 2: Markov scenarios -----------------------------------------------------------------------------------------
def events(models, p, alpha, rho, t, ep):
    """Expected events and censorings per patient by group at calendar time t."""
    out = []
    for z, m in enumerate(models):
        pts = sorted(set(x for x in list(m.time) + list(m.time_post) + [t - a for a in alpha] if 0 < x < t)) or None

        def fe(s):
            R, e = rc.group_funcs(m, s, ep)
            return rl.abar(alpha, rho, t - s) * e

        def fc(s):
            R, e = rc.group_funcs(m, s, ep)
            return rl.abar(alpha, rho, t - s) * R * r5.censor_haz(m, s, ep)
        out.append((p[z] * integrate.quad(fe, 0, t, points=pts, epsabs=1e-13, epsrel=1e-11, limit=400)[0],
                    p[z] * integrate.quad(fc, 0, t, points=pts, epsabs=1e-13, epsrel=1e-11, limit=400)[0]))
    return out


def part_cross():
    alpha, rho, _ = ACC.setup(N)
    rows, rows_ev = [], []
    for name in ("PF", "PFC"):
        models = scenario(name)
        for ep in ("pfs", "os"):
            ev = events(models, (0.5, 0.5), alpha, rho, 20.0, ep)
            rows_ev.append(dict(scenario=name, n=N, time=20.0, endpoint=ep, events_control=N * ev[0][0],
                                events_treatment=N * ev[1][0], dropouts_control=N * ev[0][1],
                                dropouts_treatment=N * ev[1][1]))
        for tp, to in ((12.0, 20.0), (20.0, 12.0)):
            t0 = time.time()
            cm = rc.cross_moments(models, (0.5, 0.5), alpha, rho, tp, to)
            for a in range(3):
                for b in range(3):
                    rows.append(dict(scenario=name, n=N, t_p=tp, t_o=to, key_p=KEYS[a], key_o=KEYS[b], value=cm[a, b]))
            print(name, tp, to, "%.0fs" % (time.time() - t0), flush=True)
    write("model5_events.csv", rows_ev)
    write("model5_cross.csv", rows)


# part 3: Monte Carlo --------------------------------------------------------------------------------------------
def _breaks(models, tmax):
    b = set([0.0, tmax])
    for m in models:
        tm, tp = list(m.time), list(m.time_post)
        c = tm + tp + [x + y for x in tm for y in tp] + [x + y for x in tp for y in tp] \
            + [x + y + z for x in tm for y in tp for z in tp]
        if m.switch_af is not None and m.switch_af != 1:
            phi = m.switch_af
            e = [(x - (1 - phi) * y) / phi for x in tp for y in tp + tm]
            c += e + [x + y for x in tm for y in e]
        b |= set(x for x in c if 0 < x < tmax)
    return np.array(sorted(b))


class Functionals:
    """rho and the integral B of beta of the three functionals, by group, on Chebyshev series between the break
    points of the group functions (computed with the reference functions of ref_cross5)."""

    def __init__(self, models, p, ep, tmax, deg=16):
        self.br = _breaks(models, tmax)
        self.segs = []
        b_start = np.zeros((2, 3))
        for lo, hi in zip(self.br[:-1], self.br[1:]):
            gf = []
            xw = cheb.chebpts1(deg + 1)
            xs = lo + (hi - lo) * (xw + 1) / 2
            for m in models:
                v = np.array([rc.group_funcs(m, x, ep) for x in xs])
                gf.append(tuple(cheb.Chebyshev(cheb.chebfit(xw, v[:, i], deg), domain=[lo, hi]) for i in (0, 1)))
            seg = dict(lo=lo, hi=hi, rho={}, B={})
            for z in (0, 1):
                def parts(x, z=z):
                    R0, e0 = gf[0][0](x), gf[0][1](x)
                    R1, e1 = gf[1][0](x), gf[1][1](x)
                    ys = p[0] * R0 + p[1] * R1
                    q = p[1] * R1 / ys
                    lb = (p[0] * e0 + p[1] * e1) / ys
                    g = 1 - q if z == 1 else -q
                    return np.array([g, q * (1 - q), 1.0 + 0 * q]), np.array([-g * lb, (1 - 2 * q) * g * lb, 0 * q])
                rho_k, b_k = [], []
                for k in range(3):
                    rho_k.append(cheb.Chebyshev.interpolate(lambda x, k=k: parts(x)[0][k], 2 * deg, domain=[lo, hi]))
                    bk = cheb.Chebyshev.interpolate(lambda x, k=k: parts(x)[1][k], 2 * deg, domain=[lo, hi]).integ(lbnd=lo)
                    b_k.append((b_start[z, k], bk))
                    b_start[z, k] += bk(hi)
                seg["rho"][z] = rho_k
                seg["B"][z] = b_k
            self.segs.append(seg)

    def value(self, z, x, event):
        """Functional values (n x 3) for observed times x and event indicators."""
        out = np.zeros((x.size, 3))
        j = np.clip(np.searchsorted(self.br, x, side="right") - 1, 0, len(self.segs) - 1)
        for i in np.unique(j):
            sel = j == i
            seg = self.segs[i]
            for k in range(3):
                b0, bk = seg["B"][z][k]
                out[sel, k] = b0 + bk(x[sel]) + np.where(event[sel], seg["rho"][z][k](x[sel]), 0.0)
        return out


def draw_entry(rng, alpha, rho, size):
    mass = rho * np.diff(alpha)
    j = rng.choice(len(mass), size=size, p=mass / mass.sum())
    return alpha[j] + rng.random(size) * (alpha[j + 1] - alpha[j])


def part_mc(n_patients=10_000_000, chunk=500_000, seed=20261024):
    alpha, rho, _ = ACC.setup(N)
    pairs = ((12.0, 20.0), (20.0, 12.0))
    rows = []
    for si, name in enumerate(("PR", "PRC", "AR", "WF")):
        t0 = time.time()
        models = scenario(name)
        tmax = 20.0
        fun = {ep: Functionals(models, (0.5, 0.5), ep, tmax) for ep in ("pfs", "os")}
        print(name, "tables %.0fs" % (time.time() - t0), flush=True)
        rng = np.random.default_rng(seed + si)
        s1 = np.zeros((len(pairs), 3, 3))
        s2 = np.zeros((len(pairs), 3, 3))
        done = 0
        while done < n_patients:
            mm = min(chunk, n_patients - done)
            z = (rng.random(mm) < 0.5).astype(int)
            e = draw_entry(rng, alpha, rho, mm)
            vals = {}
            for zz, m in enumerate(models):
                sel = np.where(z == zz)[0]
                pfs, ev, os_ = r5.simulate(m, sel.size, rng)
                c, cp = r5.draw_censoring(m, sel.size, rng)
                for t in (12.0, 20.0):
                    w = np.maximum(t - e[sel], 0.0)
                    xp = np.minimum(np.minimum(pfs, np.minimum(c, cp)), w)
                    xo = np.minimum(np.minimum(os_, c), w)
                    vals.setdefault(("pfs", t), np.zeros((mm, 3)))[sel] = \
                        fun["pfs"].value(zz, xp, ev & (pfs <= np.minimum(np.minimum(c, cp), w)))
                    vals.setdefault(("os", t), np.zeros((mm, 3)))[sel] = \
                        fun["os"].value(zz, xo, os_ <= np.minimum(c, w))
            for i, (tp, to) in enumerate(pairs):
                pr = vals[("pfs", tp)][:, :, None] * vals[("os", to)][:, None, :]
                s1[i] += pr.sum(axis=0)
                s2[i] += (pr ** 2).sum(axis=0)
            done += mm
        for i, (tp, to) in enumerate(pairs):
            est = s1[i] / done
            se = np.sqrt((s2[i] / done - est ** 2) / done)
            for a in range(3):
                for b in range(3):
                    rows.append(dict(scenario=name, n=N, t_p=tp, t_o=to, key_p=KEYS[a], key_o=KEYS[b],
                                     estimate=est[a, b], se=se[a, b], patients=done, seed=seed + si))
        print(name, "MC %.0fs" % (time.time() - t0), flush=True)
    write("model5_cross_mc.csv", rows)


if __name__ == "__main__":
    parts = sys.argv[1:] or ["model", "cross", "mc"]
    if "model" in parts:
        part_model()
    if "cross" in parts:
        part_cross()
    if "mc" in parts:
        part_mc()
