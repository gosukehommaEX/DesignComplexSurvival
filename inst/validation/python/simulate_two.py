"""Patient-level simulation of PFS and OS together (stage 2 validation: scenarios V3, V4, V6 and V7).

Written independently of the R code. Patients are generated by simulate_group() of simulate_ms.py (the generator of
V6-V8); V3 and V4 are defined here in the same way as in helpers.R. Each scenario is simulated 20000 times under the
alternative and under the global null hypothesis (the control model in both groups), with simple randomization.
Only summaries are written, to results/sim_python_two.csv (columns of sim_python.csv):

  calendar looks (look_type "calendar"): correlation of Z_PFS at look j and Z_OS at look k (quantity "z_corr_po",
    look "j-k", endpoint "pfs-os")
  design looks (look_type "design"): the two-endpoint design of the scenario (below): analysis times ("time",
    endpoint = trigger endpoint), group-wise events of both endpoints ("events"), Z of the tested statistics ("z",
    mean and standard deviation), the correlation of each pair of tested statistics ("z_corr", look "j-k",
    endpoint "e1-e2"), the efficacy bounds of each procedure computed with ref_gsd.py ("bound", group = "fs" or
    "bonferroni"), and the rejection rates of each procedure ("reject", group = procedure, endpoint = "pfs", "os",
    "both" or "any"); looks not reached are counted ("not_reached")
  per-patient covariances (look_type "perpatient", alternative hypothesis): Monte Carlo estimates from 10 million
    patients of the covariance of the standardized scores ("cov_alt"), and of the covariance ("cov_stud") and
    correlation ("corr_stud") of the influence functions of Z, of PFS at calendar look j and OS at calendar look k,
    with batch-means standard errors (40 batches); the functionals are those of ref_zeta.py (score psi and observed
    variance phi), with the per-patient mean and information estimated from the same patients
  reference (look_type "reference", V3 only): the same covariances computed deterministically with ref_zeta.py
    (Fleischer model)

Designs (also defined in helpers.R, val_designs()):
  V3  looks at 252 and 336 OS events, both endpoints tested at both looks; OS first with O'Brien-Fleming type
      spending, then PFS with Pocock type spending
  V4, V6, V7  look 1 at 330 PFS events (PFS and OS tested), look 2 at 250 OS events (OS tested); PFS first, then OS,
      both with O'Brien-Fleming type spending
  The information fractions of an endpoint are its expected events at its looks under the alternative
  (ref_logrank.py) divided by those at its last look. Procedures: fixed sequence with procedure (b) of Glimm et al.
  (2010) ("fs_overall": the second endpoint is tested from the look at which the first is rejected) and procedure (a)
  ("fs_stagewise": only at that look), each endpoint at level 0.025; Bonferroni with weights 0.8 (first endpoint)
  and 0.2 ("bonferroni"). The same bounds are used under the null hypothesis.

Usage (about 30 minutes):
  python3 simulate_two.py
  python3 simulate_two.py --scenarios V3 --reps 2000 --mc 200000 --out /tmp/x.csv
"""
import argparse, csv, os, sys, time
import numpy as np

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
import ref_gsd  # noqa: E402
import ref_logrank as rl  # noqa: E402
import ref_model as rm  # noqa: E402
import ref_zeta as rz  # noqa: E402
import simulate_ms as sm  # noqa: E402

LN2 = np.log(2.0)
SEEDS = {"V3": 32, "V4": 42, "V6": 62, "V7": 72}
PROCS = ("fs_overall", "fs_stagewise", "bonferroni")
WEIGHTS = {"fs": (1.0, 1.0), "bonferroni": (0.8, 0.2)}


# Scenarios ---------------------------------------------------------------------------------------------------------
def models(name, cls):
    """Control and treatment models of a scenario; cls is simulate_ms.Group or ref_model.Model."""
    if name == "V3":
        dr = -np.log(0.95) / 12

        def g(mp, mo):
            b = LN2 / mo
            return cls(b, prog=LN2 / mp - b, death_prog=b, dropout=dr)
        return g(3, 9), g(4.3, 12.9)
    clock, sr = {"V4": ("reset", 0.0), "V6": ("reset", 0.04), "V7": ("forward", 0.04)}[name]
    ctl = cls(0.01, time=[0, 4], prog=[0.10, 0.08], switch_prob=0.3, time_post=[0, 3], death_prog=[0.05, 0.06],
              switch_rate=sr, death_switch=[0.03, 0.035], dropout=0.005, clock=clock)
    trt = cls(0.008, time=[0, 4], prog=[0.06, 0.05], switch_prob=0.0, time_post=[0, 3], death_prog=[0.045, 0.05],
              switch_rate=0.0, dropout=0.005, clock=clock)
    return ctl, trt


def scenario(name):
    ctl, trt = models(name, sm.Group)
    if name == "V3":
        return dict(control=ctl, treatment=trt, alloc=1.0, n=482, cal=[27.0, 35.0],
                    accrual=dict(type="prop", time=[0.0], prop=[1.0], duration=23.0),
                    trigger=["os", "os"], events=[252, 336], tested=[["os", "pfs"], ["os", "pfs"]],
                    order=["os", "pfs"], sf={"os": "OF", "pfs": "Pocock"})
    return dict(control=ctl, treatment=trt, alloc=1.0, n=500, cal=[20.0, 30.0],
                accrual=dict(type="prop", time=[0.0, 6.0], prop=[0.3, 0.7], duration=18.0),
                trigger=["pfs", "os"], events=[330, 250], tested=[["pfs", "os"], ["os"]],
                order=["pfs", "os"], sf={"pfs": "OF", "os": "OF"})


def ref_scenario(name, sc):
    ctl, trt = models(name, rm.Model)
    a = sc["accrual"]
    return rl.Scenario(ctl, trt, sc["alloc"], rl.Accrual(time=a["time"], prop=a["prop"], duration=a["duration"]))


def design_bounds(name, sc):
    """Efficacy bounds of each procedure and endpoint, from the expected events under the alternative."""
    rs = ref_scenario(name, sc)
    n = sc["n"]
    times = [rl.event_time(rs, n, d, e) for e, d in zip(sc["trigger"], sc["events"])]
    exp_ev = {e: [rl.events(rs, n, t, e)["events"] for t in times] for e in ("pfs", "os")}
    out = {}
    for key, w in WEIGHTS.items():
        for i, e in enumerate(sc["order"]):
            lk = [j for j in range(len(times)) if e in sc["tested"][j]]
            dd = np.array([exp_ev[e][j] for j in lk])
            _, b = ref_gsd.bounds(dd / dd[-1], alpha=0.025 * w[i], sf_eff=sc["sf"][e])
            out[(key, e)] = (lk, b)
    return out, times, exp_ev


def rejections(Z, sc, bounds):
    """Rejections per trial of each procedure; Z[(endpoint, look)] are the statistics (nan when not reached)."""
    first, second = sc["order"]
    out = {}
    for proc in PROCS:
        key = "bonferroni" if proc == "bonferroni" else "fs"
        l1, b1 = bounds[(key, first)]
        l2, b2 = bounds[(key, second)]
        c1 = np.column_stack([Z[(first, j)] >= b1[i] for i, j in enumerate(l1)])
        c2 = np.column_stack([Z[(second, j)] >= b2[i] for i, j in enumerate(l2)])
        r1 = c1.any(axis=1)
        j1 = np.where(r1, np.asarray(l1)[np.argmax(c1, axis=1)], np.inf)
        lk2 = np.asarray(l2, float)
        if proc == "bonferroni":
            r2 = c2.any(axis=1)
        elif proc == "fs_overall":
            r2 = (c2 & (lk2[None, :] >= j1[:, None])).any(axis=1)
        else:
            r2 = (c2 & (lk2[None, :] == j1[:, None])).any(axis=1)
        out[proc] = {first: r1, second: r2, "both": r1 & r2, "any": r1 | r2}
    return out


# Trial simulation ------------------------------------------------------------------------------------------------
def run_trials(name, reps, chunk_patients=2_000_000, base_seed=20261020):
    sc = scenario(name)
    n = sc["n"]; p1 = sc["alloc"] / (1 + sc["alloc"])
    brk, mass = sm.accrual_setup(sc["accrual"], n)
    bounds, _, _ = design_bounds(name, sc)
    K = len(sc["trigger"])
    stats_tested = [(e, j) for j in range(K) for e in sc["tested"][j]]
    rows = []
    for hyp in ("alternative", "null"):
        trt_model = sc["treatment"] if hyp == "alternative" else sc["control"]
        per = max(1, chunk_patients // n)
        ss = np.random.SeedSequence([base_seed, SEEDS[name], 0 if hyp == "alternative" else 1])
        nchunk = int(np.ceil(reps / per))
        acc = {}
        for ci, child in enumerate(ss.spawn(nchunk)):
            rng = np.random.default_rng(child)
            nr = min(per, reps - ci * per)
            rep = np.repeat(np.arange(nr), n)
            entry = sm.draw_entry(rng, brk, mass, nr * n)
            trt = rng.random(nr * n) < p1
            lat = {"pfs": np.empty(nr * n), "os": np.empty(nr * n)}
            drop = np.empty(nr * n)
            for flag, g in ((False, sc["control"]), (True, trt_model)):
                ix = np.where(trt == flag)[0]
                lat["pfs"][ix], lat["os"][ix], _, drop[ix] = sm.simulate_group(rng, g, ix.size)

            def z_at(cut, ep):
                f = cut[rep] - entry
                enr = f >= 0
                tt = lat[ep]
                # compared on the calendar scale, as in kth_time(), so that the event at an event-driven cut is
                # counted (cut - entry may round below the event time)
                obs = enr & (tt <= drop) & (entry + tt <= cut[rep])
                ti = np.where(obs, tt, np.minimum(np.minimum(tt, drop), np.maximum(f, 0)))
                z = sm.logrank_z(rep[enr], ti[enr], obs[enr], trt[enr], nr)
                ev = {g: np.bincount(rep, weights=obs & (trt == flag), minlength=nr)
                      for g, flag in (("control", False), ("treatment", True))}
                return z, ev

            # calendar looks
            for j, c in enumerate(sc["cal"]):
                for ep in ("pfs", "os"):
                    acc.setdefault(("cal", ep, j), []).append(z_at(np.full(nr, c), ep)[0])
            # design looks
            for j, (trig, d) in enumerate(zip(sc["trigger"], sc["events"])):
                seen = lat[trig] <= drop
                cut = sm.kth_time(rep[seen], (entry + lat[trig])[seen], d, nr)
                acc.setdefault(("time", j), []).append(cut)
                cut_f = np.where(np.isnan(cut), np.inf, cut)
                for ep in ("pfs", "os"):
                    z, ev = z_at(cut_f, ep)
                    for g in ("control", "treatment"):
                        acc.setdefault(("events", ep, j, g), []).append(np.where(np.isnan(cut), np.nan, ev[g]))
                    if ep in sc["tested"][j]:
                        acc.setdefault(("z", ep, j), []).append(np.where(np.isnan(cut), np.nan, z))
            print("  %s %s chunk %d/%d (%d trials)" % (name, hyp, ci + 1, nchunk, nr), flush=True)
        st = {k: np.concatenate(v) for k, v in acc.items()}

        def add(look_type, look, tval, quantity, endpoint, group, x, target=""):
            x = np.asarray(x, float); ok = np.isfinite(x)
            m = x[ok].mean(); s = x[ok].std(ddof=1) if ok.sum() > 1 else 0.0
            rows.append(dict(source="python", scenario=name, hypothesis=hyp, look_type=look_type, look=look, time=tval,
                             target_events=target, quantity=quantity, endpoint=endpoint, group=group, mean=m, sd=s,
                             se=s / np.sqrt(ok.sum()), n=int(ok.sum())))

        def add_corr(look_type, look, quantity, endpoint, x, y):
            ok = np.isfinite(x) & np.isfinite(y)
            r = np.corrcoef(x[ok], y[ok])[0, 1]
            rows.append(dict(source="python", scenario=name, hypothesis=hyp, look_type=look_type, look=look,
                             time=np.nan, target_events="", quantity=quantity, endpoint=endpoint, group="", mean=r,
                             sd=np.nan, se=(1 - r ** 2) / np.sqrt(ok.sum()), n=int(ok.sum())))

        def add_prop(look_type, quantity, endpoint, group, x):
            p = float(np.mean(x))
            rows.append(dict(source="python", scenario=name, hypothesis=hyp, look_type=look_type, look="",
                             time=np.nan, target_events="", quantity=quantity, endpoint=endpoint, group=group,
                             mean=p, sd=np.nan, se=np.sqrt(p * (1 - p) / x.size), n=int(x.size)))

        for j in range(len(sc["cal"])):
            for k in range(len(sc["cal"])):
                add_corr("calendar", "%d-%d" % (j + 1, k + 1), "z_corr_po", "pfs-os",
                         st[("cal", "pfs", j)], st[("cal", "os", k)])
        for j in range(K):
            add("design", j + 1, np.nan, "time", sc["trigger"][j], "", st[("time", j)], sc["events"][j])
            for ep in ("pfs", "os"):
                for g in ("control", "treatment"):
                    add("design", j + 1, np.nan, "events", ep, g, st[("events", ep, j, g)], sc["events"][j])
            for ep in sc["tested"][j]:
                add("design", j + 1, np.nan, "z", ep, "", st[("z", ep, j)], sc["events"][j])
        for a in range(len(stats_tested)):
            for b in range(a + 1, len(stats_tested)):
                (e1, j1), (e2, j2) = stats_tested[a], stats_tested[b]
                add_corr("design", "%d-%d" % (j1 + 1, j2 + 1), "z_corr", "%s-%s" % (e1, e2),
                         st[("z", e1, j1)], st[("z", e2, j2)])
        Z = {(e, j): st[("z", e, j)] for (e, j) in stats_tested}
        rej = rejections(Z, sc, bounds)
        for proc in PROCS:
            for what, x in rej[proc].items():
                add_prop("design", "reject", what, proc, x)
        for (key, e), (lk, b) in sorted(bounds.items()):
            for i, j in enumerate(lk):
                rows.append(dict(source="python", scenario=name, hypothesis=hyp, look_type="design", look=j + 1,
                                 time=np.nan, target_events="", quantity="bound", endpoint=e, group=key, mean=b[i],
                                 sd=0.0, se=0.0, n=0))
        rows.append(dict(source="python", scenario=name, hypothesis=hyp, look_type="design", look="", time=np.nan,
                         target_events="", quantity="not_reached", endpoint="", group="",
                         mean=float(sum(np.isnan(st[("time", j)]).sum() for j in range(K))), sd=np.nan, se=np.nan,
                         n=reps))
    return rows


# Per-patient covariances -----------------------------------------------------------------------------------------
def functional_tables(rs, ep, tmax, npts=8001):
    """r1 (event observed) and r0 (censored) of psi, phi, dlt on a grid of follow-up times, per group."""
    sf = rz.SameFuncs(rs, ep, tmax)
    grid = np.linspace(0.0, tmax, npts)
    r1 = np.zeros((2, grid.size, 3)); r0 = np.zeros((2, grid.size, 3))
    for i, x in enumerate(grid):
        (p0, R0, _, _), (p1, R1, _, _) = sf._groups(x)
        q = p1 * R1 / (p0 * R0 + p1 * R1)
        yy = sf.y(x)
        for z in (0, 1):
            g = 1 - q if z == 1 else -q
            B = np.array([-yy[14 * z], yy[14 * z + 1], 0.0])
            r1[z, i] = np.array([g, q * (1 - q), 1.0]) + B
            r0[z, i] = B
    return grid, r1, r0


def perpatient(name, n_patients, batches=40, seed=20261021):
    sc = scenario(name)
    rs = ref_scenario(name, sc)
    cal = sc["cal"]; tmax = max(cal)
    tabs = {ep: functional_tables(rs, ep, tmax) for ep in ("pfs", "os")}
    brk, mass = sm.accrual_setup(sc["accrual"], sc["n"])
    rng = np.random.default_rng(np.random.SeedSequence([seed, SEEDS[name]]))
    per = n_patients // batches
    nc = len(cal)
    # per batch: sums of psi and phi of each endpoint and time, of the four products of PFS (j) and OS (k), and of
    # the products within an endpoint at the same time
    S1 = np.zeros((batches, 2, nc, 2))           # endpoint (0 pfs, 1 os), time, component (psi, phi)
    S2 = np.zeros((batches, nc, nc, 2, 2))       # pfs time j, os time k, pfs component, os component
    S3 = np.zeros((batches, 2, nc, 2, 2))        # endpoint, time, component, component
    for bi in range(batches):
        z = (rng.random(per) < sc["alloc"] / (1 + sc["alloc"])).astype(int)
        e = sm.draw_entry(rng, brk, mass, per)
        r = np.zeros((2, nc, per, 2))
        for zz, g in enumerate((sc["control"], sc["treatment"])):
            sel = np.where(z == zz)[0]
            pfs, os_, _, drop = sm.simulate_group(rng, g, sel.size)
            for ie, (ep, tt) in enumerate((("pfs", pfs), ("os", os_))):
                grid, r1, r0 = tabs[ep]
                for j, c in enumerate(cal):
                    w = np.maximum(c - e[sel], 0.0)
                    d = (tt <= drop) & (e[sel] + tt <= c)
                    x = np.where(d, tt, np.minimum(np.minimum(tt, drop), w))
                    for k in range(2):
                        r[ie, j, sel, k] = np.where(d, np.interp(x, grid, r1[zz, :, k]), np.interp(x, grid, r0[zz, :, k]))
        S1[bi] = r.sum(axis=2)
        S2[bi] = np.einsum("jna,kno->jkao", r[0], r[1])
        S3[bi] = np.einsum("ejna,ejno->ejao", r, r)
        print("  %s per-patient batch %d/%d" % (name, bi + 1, batches), flush=True)
    N = per * batches

    def estimates(s1, s2, s3, cnt):
        mm = s1 / cnt                                  # means: [endpoint, time, component]
        mu, v = mm[..., 0], mm[..., 1]                 # per-patient score mean and information
        cov = s2 / cnt - mm[0][:, None, :, None] * mm[1][None, :, None, :]   # [j, k, a, o]
        cov_same = s3 / cnt - mm[:, :, :, None] * mm[:, :, None, :]          # [e, j, a, o]
        out_alt = cov[:, :, 0, 0] / np.sqrt(v[0][:, None] * v[1][None, :])
        cf = np.stack([-1 / np.sqrt(v), mu / (2 * v ** 1.5)], axis=-1)       # [e, j, a]
        out_stud = np.einsum("ja,jkao,ko->jk", cf[0], cov, cf[1])
        var = np.einsum("eja,ejao,ejo->ej", cf, cov_same, cf)
        out_corr = out_stud / np.sqrt(var[0][:, None] * var[1][None, :])
        return out_alt, out_stud, out_corr
    est = estimates(S1.sum(axis=0), S2.sum(axis=0), S3.sum(axis=0), N)
    bat = [estimates(S1[bi], S2[bi], S3[bi], per) for bi in range(batches)]
    rows = []
    for qi, q in enumerate(("cov_alt", "cov_stud", "corr_stud")):
        b = np.array([x[qi] for x in bat])
        se = b.std(axis=0, ddof=1) / np.sqrt(batches)
        for j in range(nc):
            for k in range(nc):
                rows.append(dict(source="python", scenario=name, hypothesis="alternative", look_type="perpatient",
                                 look="%d-%d" % (j + 1, k + 1), time=np.nan, target_events="", quantity=q,
                                 endpoint="pfs-os", group="", mean=est[qi][j, k], sd=np.nan, se=se[j, k], n=N))
    return rows


def reference_v3():
    """Deterministic covariances of PFS and OS at the calendar looks of V3 (ref_zeta.py, Fleischer model)."""
    sc = scenario("V3")
    rs = ref_scenario("V3", sc)
    n = sc["n"]; cal = sc["cal"]
    alpha, rho, _ = rs.accrual.setup(n)
    ctl, trt = models("V3", rm.Model)
    groups = [rz.FleischerGroup(m.prog[0], m.death[0], m.dropout[0]) for m in (ctl, trt)]
    mom_same = {e: (list(cal),) + rz.same_moments(rs, n, cal, e) for e in ("pfs", "os")}
    mom_cross = {(tp, to): rz.cross_moments_fleischer(groups, (rs.p0, rs.p1), alpha, rho, tp, to)
                 for tp in cal for to in cal}
    core = {(e, t): rz.per_patient_core(rs, n, t, e) for e in ("pfs", "os") for t in cal}
    items = [("pfs", t, None) for t in cal] + [("os", t, None) for t in cal]
    S = rz.zeta_cov(items, mom_same, mom_cross, core)
    rows = []
    nc = len(cal)
    for j, tp in enumerate(cal):
        for k, to in enumerate(cal):
            iP, iO = mom_same["pfs"][0].index(tp), mom_same["os"][0].index(to)
            cpsi = mom_cross[(tp, to)][0, 0] - mom_same["pfs"][1][iP, 0] * mom_same["os"][1][iO, 0]
            alt = cpsi / np.sqrt(core[("pfs", tp)]["v"] * core[("os", to)]["v"])
            corr = S[j, nc + k] / np.sqrt(S[j, j] * S[nc + k, nc + k])
            for q, val in (("cov_alt", alt), ("cov_stud", S[j, nc + k]), ("corr_stud", corr)):
                rows.append(dict(source="python", scenario="V3", hypothesis="alternative", look_type="reference",
                                 look="%d-%d" % (j + 1, k + 1), time=np.nan, target_events="", quantity=q,
                                 endpoint="pfs-os", group="", mean=val, sd=0.0, se=0.0, n=0))
    return rows


COLS = ["source", "scenario", "hypothesis", "look_type", "look", "time", "target_events", "quantity", "endpoint",
        "group", "mean", "sd", "se", "n"]

if __name__ == "__main__":
    ap = argparse.ArgumentParser()
    ap.add_argument("--scenarios", default="V3,V4,V6,V7")
    ap.add_argument("--reps", type=int, default=20000)
    ap.add_argument("--mc", type=int, default=10_000_000)
    ap.add_argument("--out", default=os.path.join(HERE, "..", "results", "sim_python_two.csv"))
    a = ap.parse_args()
    allrows = []
    for nm in a.scenarios.split(","):
        t0 = time.time()
        allrows += run_trials(nm, a.reps)
        allrows += perpatient(nm, a.mc)
        if nm == "V3":
            allrows += reference_v3()
        print("%s done in %.0f s" % (nm, time.time() - t0), flush=True)
    os.makedirs(os.path.dirname(os.path.abspath(a.out)), exist_ok=True)
    with open(a.out, "w", newline="", encoding="utf-8") as fh:
        w = csv.DictWriter(fh, fieldnames=COLS, lineterminator="\n")
        w.writeheader()
        for r in allrows:
            r = dict(r)
            for k in ("mean", "sd", "se", "time"):
                if isinstance(r[k], float):
                    r[k] = "" if np.isnan(r[k]) else repr(float(r[k]))
            w.writerow(r)
    print("written", a.out, len(allrows), "rows")
