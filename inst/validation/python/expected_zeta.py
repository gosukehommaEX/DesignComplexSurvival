"""Expected values for the tests of the studentized and PFS-OS covariance (stage 2).

Run from this folder with:  python3 expected_zeta.py
Requires numpy and scipy (about 10 minutes). Results are written to results/zeta_*.csv and read by the tests
in tests/testthat (helper-expected.R).

Scenarios (defined identically in tests/testthat/helper-scenarios.R):
B, C, Cf  as in expected_values.py
F  Fleischer-type model: per group exponential progression a = log(2)/m_pfs - b and death b = log(2)/m_os
   (m_pfs = 3, 4.3; m_os = 9, 12.9), dropout 0.004 (control) and 0.006 (treatment), allocation 2:1,
   accrual 10 per month for 4 months and then 25 per month, n = 400

Files:
  zeta_same.csv   per-patient means E[r_a(t)] and products E[r_a(t1) r_b(t2)] of one endpoint
                  (a, b in psi, phi, dlt); reference: ref_zeta.same_moments (ODE and adaptive quadrature)
  zeta_cross.csv  per-patient E[r_P(t_p) r_O(t_o)] in scenario F; reference: ref_zeta.cross_moments_fleischer
  zeta_cov.csv    covariance of zeta for PFS and OS at months 12 and 20 in scenario F, for calendar times and
                  for times driven by OS or PFS events; reference: ref_zeta.zeta_cov
  zeta_cross_mc.csv  Monte Carlo estimates (10 million patients) of E[r_P(12) r_O(20)] in scenarios C and Cf,
                  with standard errors; patients generated by simulate_ms.simulate_group
"""
import csv
import os
import sys
import time

import numpy as np

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
import ref_logrank as rl  # noqa: E402
import ref_model as rm  # noqa: E402
import ref_zeta as rz  # noqa: E402
import simulate_ms as sm  # noqa: E402

OUT = os.path.join(HERE, "results")
LN2 = np.log(2.0)
KEYS = rz.KEYS


def write(name, rows):
    os.makedirs(OUT, exist_ok=True)
    path = os.path.join(OUT, name)
    keys = list(rows[0].keys())
    with open(path, "w", newline="") as f:
        w = csv.DictWriter(f, fieldnames=keys, lineterminator="\n")
        w.writeheader()
        for r in rows:
            w.writerow({k: (repr(float(v)) if isinstance(v, (float, np.floating)) else v) for k, v in r.items()})
    print("wrote", path, flush=True)


def scenario_b():
    return rl.Scenario(rm.Model(death=[0.05, 0.04], time=[0, 6], dropout=0.01),
                       rm.Model(death=[0.05, 0.025], time=[0, 6], dropout=0.012), 2.0,
                       rl.Accrual(time=[0, 3], rate=[10, 30]))


def models_c(clock, cls=rm.Model):
    ctl = cls(time=[0, 4], prog=[0.10, 0.08], death=0.01, switch_prob=0.3, time_post=[0, 3],
              death_prog=[0.05, 0.06], switch_rate=0.04, death_switch=[0.03, 0.035], dropout=0.005, clock=clock)
    trt = cls(time=[0, 4], prog=[0.06, 0.05], death=0.008, switch_prob=0.0, time_post=[0, 3],
              death_prog=[0.045, 0.05], switch_rate=0.0, dropout=0.005, clock=clock)
    return ctl, trt


def scenario_c(clock):
    ctl, trt = models_c(clock)
    return rl.Scenario(ctl, trt, 1.0, rl.Accrual(time=[0, 6], prop=[0.3, 0.7], duration=18))


F_RATES = dict(b=(LN2 / 9, LN2 / 12.9), mpfs=(3.0, 4.3), drop=(0.004, 0.006))


def scenario_f():
    b0, b1 = F_RATES["b"]
    a0, a1 = LN2 / 3 - b0, LN2 / 4.3 - b1
    return rl.Scenario(rm.Model(b0, prog=a0, death_prog=b0, dropout=0.004),
                       rm.Model(b1, prog=a1, death_prog=b1, dropout=0.006), 2.0,
                       rl.Accrual(time=[0, 4], rate=[10, 25]))


def groups_f():
    b0, b1 = F_RATES["b"]
    return [rz.FleischerGroup(LN2 / 3 - b0, b0, 0.004), rz.FleischerGroup(LN2 / 4.3 - b1, b1, 0.006)], (1 / 3, 2 / 3)


def part_same():
    rows = []
    for name, scn, n, times, ep in (("B", scenario_b(), 300, [15.0, 25.0], "os"),
                                    ("C", scenario_c("reset"), 500, [10.0, 20.0], "pfs"),
                                    ("C", scenario_c("reset"), 500, [20.0, 30.0], "os"),
                                    ("Cf", scenario_c("forward"), 500, [20.0, 30.0], "os")):
        t0 = time.time()
        mean, prod = rz.same_moments(scn, n, times, ep)
        for i, t in enumerate(times):
            for a in range(3):
                rows.append(dict(scenario=name, n=n, endpoint=ep, quantity="mean", time1=t, time2=t,
                                 key1=KEYS[a], key2="", value=mean[i, a]))
        for i, t1 in enumerate(times):
            for j, t2 in enumerate(times):
                for a in range(3):
                    for b in range(3):
                        rows.append(dict(scenario=name, n=n, endpoint=ep, quantity="prod", time1=t1, time2=t2,
                                         key1=KEYS[a], key2=KEYS[b], value=prod[i, j, a, b]))
        print(name, ep, "%.0fs" % (time.time() - t0), flush=True)
    write("zeta_same.csv", rows)


def part_cross_cov():
    scn = scenario_f()
    n = 400
    alpha, rho, _ = scn.accrual.setup(n)
    groups, p = groups_f()
    times = [12.0, 20.0]
    t0 = time.time()
    rows = []
    mom_cross = {}
    for tp in times:
        for to in times:
            cm = rz.cross_moments_fleischer(groups, p, alpha, rho, tp, to)
            mom_cross[(tp, to)] = cm
            for a in range(3):
                for b in range(3):
                    rows.append(dict(scenario="F", n=n, t_p=tp, t_o=to, key_p=KEYS[a], key_o=KEYS[b], value=cm[a, b]))
    write("zeta_cross.csv", rows)
    mom_same = {ep: (times,) + rz.same_moments(scn, n, times, ep) for ep in ("pfs", "os")}
    core = {(ep, t): rz.per_patient_core(scn, n, t, ep) for ep in ("pfs", "os") for t in times}
    rows = []
    for trig in (None, "os", "pfs"):
        items = [(ep, t, trig) for ep in ("pfs", "os") for t in times]
        S = rz.zeta_cov(items, mom_same, mom_cross, core)
        for i, (ei, ti, _) in enumerate(items):
            for j, (ej, tj, _) in enumerate(items):
                rows.append(dict(scenario="F", n=n, trigger=trig or "calendar", row=i + 1, col=j + 1,
                                 endpoint_row=ei, time_row=ti, endpoint_col=ej, time_col=tj, value=S[i, j]))
    write("zeta_cov.csv", rows)
    print("cross and cov %.0fs" % (time.time() - t0), flush=True)


def part_mc(n_patients=10_000_000, chunk=500_000, seed=20261020):
    tp, to = 12.0, 20.0
    grid = np.linspace(0.0, to, 8001)
    rows = []
    rng = np.random.default_rng(seed)
    brk, mass = sm.accrual_setup(dict(type="prop", time=[0, 6], prop=[0.3, 0.7], duration=18), 500)
    for name, clock in (("C", "reset"), ("Cf", "forward")):
        t0 = time.time()
        scn = scenario_c(clock)
        tabs = {}
        for ep in ("pfs", "os"):
            sf = rz.SameFuncs(scn, ep, to)
            r1 = np.zeros((2, grid.size, 3))
            r0 = np.zeros((2, grid.size, 3))
            for i, x in enumerate(grid):
                (p0, R0, _, _), (p1, R1, _, _) = sf._groups(x)
                q = p1 * R1 / (p0 * R0 + p1 * R1)
                yy = sf.y(x)
                for z in (0, 1):
                    g = 1 - q if z == 1 else -q
                    B = np.array([-yy[14 * z], yy[14 * z + 1], 0.0])
                    r1[z, i] = np.array([g, q * (1 - q), 1.0]) + B
                    r0[z, i] = B
            tabs[ep] = (r1, r0)

        def functional(ep, z, x, d):
            r1, r0 = tabs[ep]
            return np.column_stack([np.where(d, np.interp(x, grid, r1[z, :, k]), np.interp(x, grid, r0[z, :, k]))
                                    for k in range(3)])
        s1 = np.zeros((3, 3))
        s2 = np.zeros((3, 3))
        done = 0
        groups = models_c(clock, cls=sm.Group)
        while done < n_patients:
            m = min(chunk, n_patients - done)
            z = (rng.random(m) < 0.5).astype(int)
            e = sm.draw_entry(rng, brk, mass, m)
            rp = np.zeros((m, 3))
            ro = np.zeros((m, 3))
            for zz, g in enumerate(groups):
                sel = np.where(z == zz)[0]
                pfs, os_, _, drop = sm.simulate_group(rng, g, sel.size)
                wp = np.maximum(tp - e[sel], 0.0)
                wo = np.maximum(to - e[sel], 0.0)
                rp[sel] = functional("pfs", zz, np.minimum(np.minimum(pfs, drop), wp), pfs <= np.minimum(drop, wp))
                ro[sel] = functional("os", zz, np.minimum(np.minimum(os_, drop), wo), os_ <= np.minimum(drop, wo))
            pr = rp[:, :, None] * ro[:, None, :]
            s1 += pr.sum(axis=0)
            s2 += (pr ** 2).sum(axis=0)
            done += m
        est = s1 / done
        se = np.sqrt((s2 / done - est ** 2) / done)
        for a in range(3):
            for b in range(3):
                rows.append(dict(scenario=name, n=500, t_p=tp, t_o=to, key_p=KEYS[a], key_o=KEYS[b],
                                 estimate=est[a, b], se=se[a, b], patients=done, seed=seed))
        print(name, "MC %.0fs" % (time.time() - t0), flush=True)
    write("zeta_cross_mc.csv", rows)


if __name__ == "__main__":
    parts = sys.argv[1:] or ["same", "cross", "mc"]
    if "same" in parts:
        part_same()
    if "cross" in parts:
        part_cross_cov()
    if "mc" in parts:
        part_mc()
